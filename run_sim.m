    figurePixels = getpixelposition(fig,true);
    leftPixels = plot_box_pixels(axLeft);
    rightPixels = plot_box_pixels(axRight);

    leftPosition = [ ...
        leftPixels(1:2)./figurePixels(3:4), ...
        leftPixels(3:4)./figurePixels(3:4)];


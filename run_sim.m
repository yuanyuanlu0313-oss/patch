    30.20;
    28.60;
    26.40;
    22.80;
    25.20;
    29.60;
    27.40;
    23.80;
    28.20;
    24.80];

p.gamma = [ ...
    0.10;
    0.11;
    0.12;
    0.09;
    0.10;
    0.13;
    0.11;
    0.09;
    0.12;
    0.10];

p.muA = ...
    0.01*ones(p.n,1);


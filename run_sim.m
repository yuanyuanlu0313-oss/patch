    yRangeForMap = yRange;
    yLimitsForMap = yLimits;
end

boxRight = ...
    leftPosition(1) + ...
    leftPosition(3) * ...
    (xRangeForMap(2)-xLimitsForMap(1)) / ...
    diff(xLimitsForMap);

boxBottom = ...
    leftPosition(2) + ...
    leftPosition(4) * ...
    (yRangeForMap(1)-yLimitsForMap(1)) / ...
    diff(yLimitsForMap);


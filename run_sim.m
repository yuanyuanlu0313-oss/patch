    axLeft, ...
    'Position',[ ...
        xRange(1), ...
        yRange(1), ...
        diff(xRange), ...
        diff(yRange)], ...
    'EdgeColor','k', ...
    'LineWidth',1.25, ...
    'LineStyle','-');


            allR = rzero_ppf_batch( ...
                p,DM0,DF0, ...
                subsets,dose,logSlope);

            [lastR,lastIndex] = min(allR);

            lastDose = dose;
        end

        selectedPatches = subsets(lastIndex,:);

        Rbest(k,ib) = lastR;

        bestSet{k,ib} = selectedPatches;
    end
end


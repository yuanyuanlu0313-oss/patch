    p.gamma+p.muA;

p.K = [ ...
    24;
    18;
    22;
    16;
    26;
    19;
    23;
    17;
    25;
    20];

p.muM = [ ...
    0.13;
    0.12;
    0.14;
    0.15;
    0.11;
    0.13;
    0.12;
    0.15;
    0.11;
    0.14];

p.muF = [ ...
    0.07;
    0.06;
    0.07;
    0.07;
    0.05;
    0.07;
    0.06;
    0.07;
    0.05;
    0.07];

ellPlus = [ ...
    0.62;
    0.58;
    0.65;
    0.55;
    0.60;
    0.64;
    0.57;
    0.63;
    0.56;
    0.61];

ellMinus = ...
    1-ellPlus;

p.L = ...
    zeros(p.n);

for j = 1:p.n

    jp = ...
        mod(j,p.n)+1;

    jm = ...
        mod(j-2,p.n)+1;

    p.L(jp,j) = ...
        ellPlus(j);

    p.L(jm,j) = ...
        ellMinus(j);

    p.L(j,j) = -1;
end

assert( ...
    norm(ones(1,p.n)*p.L,inf)<1e-13, ...
    'Columns of L must sum to zero.');

end

function s = ...
    make_scenario( ...
        name,rho,muM,muF, ...
        ppf,male,female)

s = struct( ...
    'name',name, ...
    'rho',rho, ...
    'muM',muM, ...
    'muF',muF, ...
    'ppf',ppf, ...
    'male',male, ...
    'female',female);

end

function [AM,AF] = ...
    adult_maps( ...
        p,DM,DF,muM,muF)

AM = ...
    p.theta * ...
    ((diag(muM)-DM*p.L) \ ...
     diag(p.gamma));

AF = ...
    (1-p.theta) * ...
    ((diag(muF)-DF*p.L) \ ...
     diag(p.gamma));

end

function y = ...
    threshold_from_maps( ...
        p,x,rho,AM,AF)

M = AM*x;
F = AF*x;

H = ...
    (M.*F)./(M+F);

y = ...
    (rho./p.c).*H;

end

function R = ...
    rzero_power( ...
        p,DM,DF,rho,muM,muF,x0)

[AM,AF] = ...
    adult_maps( ...
        p,DM,DF,muM,muF);

if isempty(x0)
    x = ones(p.n,1);
else
    x = max(x0,realmin);
end

x = ...
    x/(p.gamma'*x);

tol = 1e-11;

for it = 1:50000

    y = ...
        threshold_from_maps( ...
            p,x,rho,AM,AF);

    R = ...
        p.gamma'*y;

    xn = ...
        y/R;

    if norm(xn-x,inf)<tol
        return
    end
    x = ...
        0.5*x+0.5*xn;

    x = ...
        x/(p.gamma'*x);
end

error( ...
    'The damped nonlinear power iteration did not converge.');

end

function Rall = ...
    rzero_ppf_batch( ...
        p,DM,DF, ...
        subsets,dose,logSlope)

[AM,AF] = ...
    adult_maps( ...
        p,DM,DF,p.muM,p.muF);

m = ...
    size(subsets,1);

rhoMat = ...
    repmat(p.rho,1,m);

factor = ...
    exp(logSlope*dose);

for j = 1:m
    rhoMat(subsets(j,:),j) = ...
        factor .* ...
        rhoMat(subsets(j,:),j);
end

X = ...
    ones(p.n,m);

X = ...
    X./(p.gamma'*X);

for it = 1:2000

    M = AM*X;
    F = AF*X;

    Y = ...
        (rhoMat./p.c) .* ...
        ((M.*F)./(M+F));

    Rall = ...
        p.gamma'*Y;

    Xn = ...
        Y./Rall;

    if max(abs(Xn-X),[],'all')<1e-11
        return
    end

    X = Xn;
end

error( ...
    'Batched PPF power iteration did not converge.');

end

function [R,xBest] = ...
    rzero_multistart( ...
        p,DM,DF,rho,muM,muF,xPrevious)

[AM,AF] = ...
    adult_maps( ...
        p,DM,DF,muM,muF);

seeds = ...
    zeros(p.n-1,0);

if ~isempty(xPrevious)
    seeds(:,end+1) = ...
        log( ...
            max(xPrevious(1:end-1),realmin) ./ ...
            max(xPrevious(end),realmin));
end

seeds(:,end+1) = ...
    zeros(p.n-1,1);

for j = 1:p.n

    seedProfile = ...
        1e-4*ones(p.n,1);

    seedProfile(j) = 1;

    seeds(:,end+1) = ...
        log( ...
            seedProfile(1:end-1) ./ ...
            seedProfile(end));
end

candidateR = [];
candidateX = {};

for j = 1:size(seeds,2)

    [ok,Rj,xj] = ...
        newton_eigenpair( ...
            p,rho,AM,AF, ...
            seeds(:,j));

    if ok
        candidateR(end+1,1) = ...
            Rj;
        candidateX{end+1,1} = ...
            xj;
    end
end

if isempty(candidateR)

    R = ...
        rzero_power( ...
            p,DM,DF, ...
            rho,muM,muF, ...
            xPrevious);

    [~,~,xBest] = ...
        power_eigenvector( ...
            p,rho,AM,AF, ...
            xPrevious);

else

    [R,j] = ...
        max(candidateR);

    xBest = ...
        candidateX{j};
end

end

function [ok,R,x] = ...
    newton_eigenpair( ...
        p,rho,AM,AF,u)

ok = false;
R = NaN;
x = [];

for it = 1:70

    [f,x,y] = ...
        eigen_residual( ...
            p,rho,AM,AF,u);

    nf = ...
        norm(f,inf);

    if nf<1e-10

        ratio = ...
            y./x;

        if max(log(ratio)) - ...
                min(log(ratio)) < 1e-7

            R = ...
                p.gamma'*y;

            ok = ...
                isfinite(R) && R>0;
        end

        return
    end

    h = 1e-5;
    J = zeros(p.n-1);

    for j = 1:p.n-1

        uj = u;
        uj(j) = uj(j)+h;

        fj = ...
            eigen_residual( ...
                p,rho,AM,AF,uj);

        J(:,j) = ...
            (fj-f)/h;
    end

    if rcond(J)<1e-12
        step = -pinv(J)*f;
    else
        step = -J\f;
    end

    step = ...
        step / ...
        max(1,norm(step,inf)/5);

    alpha = 1;
    accepted = false;

    for ls = 1:25

        trial = ...
            max( ...
                min( ...
                    u+alpha*step, ...
                    50), ...
                -50);

        ft = ...
            eigen_residual( ...
                p,rho,AM,AF,trial);

        if norm(ft,inf) < ...
                nf*(1-1e-4*alpha)

            u = trial;
            accepted = true;
            break
        end

        alpha = ...
            alpha/2;
    end

    if ~accepted
        return
    end
end

end

function [f,x,y] = ...
    eigen_residual( ...
        p,rho,AM,AF,u)

positiveProfile = [ ...
    exp(max(min(u,50),-50));
    1];

x = ...
    positiveProfile / ...
    (p.gamma'*positiveProfile);

y = ...
    threshold_from_maps( ...
        p,x,rho,AM,AF);

r = ...
    log(y./x);

f = ...
    r(1:end-1)-r(end);

end

function [R,it,x] = ...
    power_eigenvector( ...
        p,rho,AM,AF,x0)

if isempty(x0)
    x = ones(p.n,1);
else
    x = max(x0,realmin);
end

x = ...
    x/(p.gamma'*x);

for it = 1:200000

    y = ...
        threshold_from_maps( ...
            p,x,rho,AM,AF);

    R = ...
        p.gamma'*y;

    xn = ...
        y/R;

    if norm(xn-x,inf)<1e-9
        x = xn;
        return
    end

    x = ...
        0.5*x+0.5*xn;

    x = ...
        x/(p.gamma'*x);
end

error( ...
    'Fallback power iteration did not converge.');

end

function Y = ...
    positive_equilibrium( ...
        p,DM,DF,rho,muM,muF,R)

if R<=1+1e-10
    Y = NaN;
    return
end

[AM,AF] = ...
    adult_maps( ...
        p,DM,DF,muM,muF);

A = p.K;

for it = 1:100000

    T = ...
        threshold_from_maps( ...
            p,A,rho,AM,AF);

    An = ...
        p.K.*T ./ ...
        (p.K+T);

    if norm(An-A,inf)<1e-10
        A = An;
        break
    end

    A = An;
end

if it==100000
    error( ...
        'Positive-equilibrium iteration did not converge.');
end

M = AM*A;
F = AF*A;

Y = ...
    sum(A+M+F);

end

